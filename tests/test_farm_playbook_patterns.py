class RememberingTests(unittest.TestCase):
    DEAD = [(1, 0), (3, 2), (0, 3)]

    def dead_world(self, e):
        w = world_for(e, Expand=3)  # 4 by 4
        for tile in w.tiles:
            ripe(tile, "Pumpkin")
            tile.infected = True  # a new planting clears it: told apart from the ones left alone
        for x, y in self.DEAD:
            w.at(x, y).entity = "Dead_Pumpkin"
        w._changed()
        return w

    def test_the_list_finds_the_dead_pumpkins_a_full_scan_would(self) -> None:
        e = BY_ID["remember-spots"]
        tail = {"original": ("replant(find_dead())", "quick_print(find_dead())"),
                "python": ("replant(find_dead())", "quick_print(find_dead())"),
                "javascript": ("replant(findDead());", "quickPrint(findDead());"),
                "dart": ("replant(findDead());", "quickPrint(findDead());")}
        for language in LANGUAGES:
            with self.subTest(language=language):
                w = self.dead_world(e)
                w.unlocks["Debug"] = 1
                old, new = tail[language]
                h, status = run(w, language, calling(e.snippets[language], old, new))
                ok(h, status)
                found = ints(" ".join(said(h)))
                self.assertEqual([tuple(found[i:i + 2]) for i in range(0, len(found), 2)],
                                 sorted(self.DEAD))  # column by column, as a scan goes

    def test_replanting_goes_only_to_the_dead_ones(self) -> None:
        e = BY_ID["remember-spots"]
        for language in LANGUAGES:
            with self.subTest(language=language):
                w = self.dead_world(e)
                carrots = w.items["Carrot"]
                h, status = run(w, language, e.snippets[language])
                ok(h, status)
                for tile in w.tiles:
                    self.assertEqual(tile.entity, "Pumpkin")
                planted = {(x, y) for x in range(4) for y in range(4) if not w.at(x, y).infected}
                self.assertEqual(planted, set(self.DEAD))
                # The other thirteen were never touched, and exactly three were paid for.
                self.assertEqual(sum(t.infected for t in w.tiles), 13)
                self.assertEqual(carrots - w.items["Carrot"], 3)

    def test_the_sunflowers_filed_by_petals_are_harvested_biggest_first(self) -> None:
        e = BY_ID["remember-petals"]
        petals = [15, 15, 14, 13, 12, 12, 11, 10, 10, 9, 9, 8, 8, 7, 7, 7]
        n = 4
        # Sixteen flowers: the first seven harvests each have ten or more standing.
        bonus_ceiling = 7 * data.SUNFLOWER_BONUS + 9
        for language in LANGUAGES:
            for seed in (5, 6) if language in OLD else (5,):
                with self.subTest(language=language, seed=seed):
                    w = world_for(e, Expand=3, items={})
                    order = list(petals)
                    random.Random(seed).shuffle(order)
                    for tile, count in zip(w.tiles, order):
                        ripe(tile, "Sunflower", petals=count)
                    moved = count_moves(w)
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    self.assertFalse(any(t.entity == "Sunflower" for t in w.tiles))
                    self.assertFalse(w.sunflower_spoiled)
                    self.assertGreater(w.items["Power"], bonus_ceiling - 12)
                    # Nine whole sweeps, one for each petal count, would be 9 * n * n moves.
                    self.assertLess(moved[0], 9 * n * n)

    def test_a_set_of_ids_counts_the_separate_pumpkins(self) -> None:
        e = BY_ID["remember-giants"]

        def whole(w):
            pass

        def one_unripe(w):
            w.at(2, 2).need, w.at(2, 2).grown = 900.0, 0.0

        def holes(w):
            w.at(1, 1).entity = "Dead_Pumpkin"
            w.at(3, 0).entity = None

        def stripes(w):
            for y in range(4):
                w.at(2, y).need, w.at(2, y).grown = 900.0, 0.0

        for language in LANGUAGES:
            changes = (whole, one_unripe, holes, stripes) if language in OLD else (whole, one_unripe)
            for change in changes:
                with self.subTest(language=language, field=change.__name__):
                    w = world_for(e, Expand=3, Debug=1)
                    pumpkin_field(w)
                    change(w)
                    w._changed()
                    groups = w.pumpkin_groups()
                    separate = {groups.get((t_x, t_y), (t_x, t_y, 1))[:2]
                                for t_x in range(4) for t_y in range(4)
                                if w.at(t_x, t_y).entity == "Pumpkin"}
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    self.assertEqual(ints(lines_with(h, "separate"))[0], len(separate))
                    if change is whole:
                        self.assertEqual(len(separate), 1)  # one giant

    def test_the_census_counts_each_kind_in_a_dictionary(self) -> None:
        e = BY_ID["remember-census"]
        for language in LANGUAGES:
            for bushes in ((5, 0) if language in OLD else (5,)):
                with self.subTest(language=language, bushes=bushes):
                    w = world_for(e, Expand=3)
                    for tile in w.tiles[:bushes]:
                        ripe(tile, "Bush")
                        tile.ground = "Grassland"
                    for tile in w.tiles[bushes:bushes + 3]:
                        tile.entity, tile.need, tile.grown = None, 0.0, 0.0
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    grass = sum(t.entity == "Grass" for t in w.tiles)
                    self.assertEqual(ints(lines_with(h, "grass"))[-1], grass)
                    self.assertEqual(ints(lines_with(h, "bushes"))[-1], bushes)
                    self.assertEqual(grass, 16 - bushes - 3)


# ── Maze search ─────────────────────────────────────────────────────────


class MazeSearchTests(unittest.TestCase):
    def test_depth_first_with_a_stack_reaches_the_treasure_in_new_and_reused_mazes(self) -> None:
        e = BY_ID["maze-dfs"]
        for language in LANGUAGES:
            for seed in range(1, 6) if language in OLD else (1,):
                for loops in (0, 6):
                    with self.subTest(language=language, seed=seed, loops=loops):
                        w = maze_world(e, seed, loops)
                        treasure = w.maze.treasure
                        h, status = run(w, language, e.snippets[language])
                        ok(h, status)
                        self.assertEqual((w.x, w.y), treasure)
                        self.assertEqual(w.items["Gold"], 16)  # 4 by 4: the area, paid once
                        self.assertIsNone(w.maze)

    def test_it_grows_its_own_maze_from_the_bush_and_copes_with_a_big_one(self) -> None:
        e = BY_ID["maze-dfs"]
        for language, expand, size in [(lang, 3, 4) for lang in LANGUAGES] + [("python", 7, 12)]:
            with self.subTest(language=language, size=size):
                w = world_for(e, seed=3, items={"Weird_Substance": 500}, Expand=expand)
                h, status = run(w, language, e.snippets[language])
                ok(h, status)
                self.assertEqual(w.items["Gold"], size * size)
                self.assertEqual(w.items["Weird_Substance"], 500 - size)

    def test_the_map_has_every_square_and_costs_four_moves_a_passage(self) -> None:
        e = BY_ID["maze-map"]
        for language in LANGUAGES:
            for loops in (0, 5) if language in OLD else (0,):
                with self.subTest(language=language, loops=loops):
                    w = maze_world(e, 2, loops)
                    passages = len(w.maze.open)
                    start = (w.x, w.y)
                    moved = count_moves(w)
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    self.assertEqual(ints(lines_with(h, "mapped"))[0], 16)
                    # Each passage is gone down and back from both of its ends.
                    self.assertEqual(moved[0], 4 * passages)
                    self.assertEqual((w.x, w.y), start)
                    if loops:
                        self.assertGreater(passages, 15)  # more than a tree: the maze has loops

    def test_breadth_first_walks_the_shortest_way_and_no_further_than_depth_first(self) -> None:
        bfs, dfs = BY_ID["maze-shortest"], BY_ID["maze-dfs"]
        shorter = 0
        for language in LANGUAGES:
            for seed in range(1, 6) if language in OLD else (1,):
                for loops in (0, 8):
                    with self.subTest(language=language, seed=seed, loops=loops):
                        a = maze_world(bfs, seed, loops)
                        b = maze_world(dfs, seed, loops)
                        treasure, start = a.maze.treasure, (a.x, a.y)
                        self.assertEqual((b.maze.treasure, (b.x, b.y)), (treasure, start))
                        shortest = maze_distance(a, start)
                        passages = len(a.maze.open)
                        walked_a, walked_b = count_moves(a), count_moves(b)
                        h, status = run(a, language, bfs.snippets[language])
                        ok(h, status)
                        self.assertEqual((a.x, a.y), treasure)
                        # Everything past the mapping is the walk to the treasure.
                        self.assertEqual(walked_a[0] - 4 * passages, shortest)
                        h, status = run(b, language, dfs.snippets[language])
                        ok(h, status)
                        self.assertLessEqual(shortest, walked_b[0])
                        shorter += shortest < walked_b[0]
        # Depth-first backtracks out of dead ends; somewhere it must have walked further.
        self.assertGreater(shorter, 0)


