# ── Helpers ─────────────────────────────────────────────────────────────


def ok(h: FarmHost, status: str) -> None:
    if status != "done":
        raise AssertionError(explain(h, status))


def ints(text: str) -> list[int]:
    return [int(v) for v in re.findall(r"-?\d+", text)]


def floats(text: str) -> list[float]:
    return [float(v) for v in re.findall(r"-?\d+(?:\.\d+)?", text)]


def lines_with(h: FarmHost, word: str) -> str:
    """The one line of output that has `word` in it."""
    found = [line for line in said(h) if word in line]
    assert len(found) == 1, (word, said(h))
    return found[0]


def count_moves(w) -> list[int]:
    """Count the moves the drones really make (a blocked move does not count)."""
    box = [0]
    real = w._move

    def counting(direction):
        done = real(direction)
        if done:
            box[0] += 1
        return done

    w._move = counting
    return box


def count_calls(w, name: str) -> list[int]:
    """How many times the farm is asked for `name` (a command like "till")."""
    box = [0]
    real = getattr(w, "_do_" + name)

    def counting(args, language):
        box[0] += 1
        return real(args, language)

    setattr(w, "_do_" + name, counting)
    return box


def harvest_log(w) -> list[tuple[str | None, bool]]:
    """Every harvest the drones make: what was under the drone, and whether it was ripe.
    (Counting harvests, not the barn: a plant next door that it likes pays five times.)"""
    log: list[tuple[str | None, bool]] = []
    real = w._harvest_here

    def logging():
        tile = w.here()
        log.append((tile.entity, tile.ripe))
        return real()

    w._harvest_here = logging
    return log


def growing_times(w, entity: str) -> list[float]:
    """The growing time (seconds) each new plant of `entity` is given."""
    seen: list[float] = []
    real = w._grow_time

    def timing(kind):
        value = real(kind)
        if kind == entity:
            seen.append(value)
        return value

    w._grow_time = timing
    return seen


def run_files(world, language: str, files: dict[str, str], entry: str = "main"):
    """Run a program of several files, the way the Run button does."""
    h = FarmHost()
    h._load()
    h.language = language  # the farm under test is this language's own
    h.warp = 0
    h.world = world
    h.save = lambda language=None: None
    for name, text in files.items():
        if name != entry:
            added = h.file_op(language, "add", name)
            assert added["ok"], added
            h.keep_code(language, text, name)
    started = h.start(language, files[entry], entry)
    if not started["ok"]:
        return h, f"refused: {started}"
    return h, finish(h, 180)


def torus_walk(n: int, start: tuple[int, int]) -> dict[tuple[int, int], int]:
    """Moves from `start` to every tile of an n by n wrapping field, found by walking it."""
    dist = {start: 0}
    todo = deque([start])
    while todo:
        x, y = todo.popleft()
        for dx, dy in ((0, 1), (1, 0), (0, -1), (-1, 0)):
            there = ((x + dx) % n, (y + dy) % n)
            if there not in dist:
                dist[there] = dist[(x, y)] + 1
                todo.append(there)
    return dist


def maze_distance(w, start: tuple[int, int]) -> int:
    """Moves from `start` to the treasure through the maze's open passages."""
    dist = {start: 0}
    todo = deque([start])
    while todo:
        here = todo.popleft()
        for there in w.neighbours(*here).values():
            if there not in dist and w.maze.passable(here, there):
                dist[there] = dist[here] + 1
                todo.append(there)
    return dist[w.maze.treasure]


def maze_world(e, seed: int, loops: int = 0, at=(1, 2), expand: int = 3):
    """A grown maze with the drone in it. With loops, the treasure has been moved
    that many times, and each move opened a hedge or two."""
    w = world_for(e, seed=seed, items={"Weird_Substance": 500}, Expand=expand)
    w.x, w.y = at
    w._grow_maze(w.w, w.w)
    for _ in range(loops):
        w._move_treasure()
    while w.maze.treasure == at:
        w._move_treasure()
    w.items["Gold"] = 0
    return w


