def snake(n: int) -> list[tuple[int, int]]:
    """Up the first column, down the next, and so on."""
    return [(x, y if x % 2 == 0 else n - 1 - y) for x in range(n) for y in range(n)]


def spiral(n: int) -> list[tuple[int, int]]:
    """From the bottom-left corner, North first, turning right at a wall or a visited square."""
    steps = [(0, 1), (1, 0), (0, -1), (-1, 0)]
    seen = {(0, 0)}
    order = [(0, 0)]
    x = y = d = 0
    while True:
        for turn in range(2):
            nx, ny = x + steps[d][0], y + steps[d][1]
            if 0 <= nx < n and 0 <= ny < n and (nx, ny) not in seen:
                break
            d = (d + 1) % 4
        else:
            return order
        x, y = nx, ny
        seen.add((x, y))
        order.append((x, y))


def visited(h: FarmHost) -> list[tuple[int, int]]:
    return [tuple(ints(line)) for line in said(h)]


class ScanOrderTests(unittest.TestCase):
    def test_a_sweep_comes_home_in_n_squared_moves_on_an_even_field_and_one_more_on_an_odd_one(self) -> None:
        e = BY_ID["scan-loop"]
        for language in LANGUAGES:
            for expand, n in ((3, 4), (2, 3)):
                with self.subTest(language=language, n=n):
                    w = world_for(e, Expand=expand)
                    moved = count_moves(w)
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    self.assertEqual(visited(h), snake(n))
                    self.assertEqual(moved[0], n * n if n % 2 == 0 else n * n + 1)
                    self.assertEqual((w.x, w.y), (0, 0))

    def test_the_spiral_visits_every_tile_once_ending_in_the_middle(self) -> None:
        e = BY_ID["scan-spiral"]
        cases = {"original": (2, 3, 4), "python": (2, 3, 4)}
        for language in LANGUAGES:
            for expand in cases.get(language, (3,)):
                n = data.FARM_SIZES[expand][0]
                with self.subTest(language=language, n=n):
                    w = world_for(e, Expand=expand)
                    moved = count_moves(w)
                    h, status = run(w, language, e.snippets[language])
                    ok(h, status)
                    tiles = visited(h)
                    self.assertEqual(tiles, spiral(n))
                    self.assertEqual(len(set(tiles)), n * n)
                    self.assertEqual(moved[0], n * n - 1)  # the same as a zig-zag
                    for a, b in zip(tiles, tiles[1:]):
                        self.assertEqual(abs(a[0] - b[0]) + abs(a[1] - b[1]), 1)

    def test_the_distance_is_the_moves_a_walk_takes_and_the_nearest_is_the_closest(self) -> None:
        e = BY_ID["scan-distance"]
        n = 6
        spots = {
            "original": lambda lst: "[" + ", ".join(f"({a}, {b})" for a, b in lst) + "]",
            "python": lambda lst: "[" + ", ".join(f"({a}, {b})" for a, b in lst) + "]",
            "javascript": lambda lst: "[" + ", ".join(f"[{a}, {b}]" for a, b in lst) + "]",
            "dart": lambda lst: "[" + ", ".join(f"({a}, {b})" for a, b in lst) + "]",
        }
        original = [(5, 5), (2, 1), (4, 4)]
        cases = [((1, 1), (5, 5), original), ((5, 4), (0, 0), [(1, 1), (3, 5), (4, 2)]),
                 ((0, 0), (3, 3), [(4, 4), (5, 0), (2, 5)]), ((2, 2), (2, 2), [(3, 3), (0, 5)])]
        for language in LANGUAGES:
            for start, target, listed in cases[: 4 if language in OLD else 2]:
                with self.subTest(language=language, start=start, target=target):
                    w = world_for(e, Expand=4)
                    self.assertEqual(w.w, n)
                    w.x, w.y = start
                    code = calling(e.snippets[language], "distance(5, 5)", f"distance({target[0]}, {target[1]})")
                    code = calling(code, spots[language](original), spots[language](listed))
                    h, status = run(w, language, code)
                    ok(h, status)
                    walk = torus_walk(n, start)
                    self.assertEqual(ints(lines_with(h, "moves to"))[-1], walk[target])
                    # The first of the closest wins a tie; the example's own order decides.
                    best = min(range(len(listed)), key=lambda i: (walk[listed[i]], i))
                    self.assertEqual(ints(lines_with(h, "nearest"))[-2:], list(listed[best]))


