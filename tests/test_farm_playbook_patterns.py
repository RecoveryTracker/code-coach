    def test_simulate_races_two_ways_and_leaves_the_real_farm_alone(self) -> None:
        e = BY_ID["measure-simulate"]
        n = 4  # the research the example hands the trial: Expand 3, a 4 by 4 field
        # Moves, then the questions each way asks (num_unlocked, and get_world_size once for the
        # outer loop and once for each column) - a tick each.
        asked = (2 + n)
        naive = (n * (n + 1) * data.ACTION_TICKS + asked) / data.BASE_TICKS_PER_SECOND  # a lap of every column
        zig_zag = (n * n * data.ACTION_TICKS + asked) / data.BASE_TICKS_PER_SECOND
        for language in LANGUAGES:
            with self.subTest(language=language):
                w = world_for(e, items={"Hay": 7})
                items, tiles = dict(w.items), [(t.entity, t.ground) for t in w.tiles]
                h, status = run(w, language, e.snippets[language])
                ok(h, status)
                slack = 0.0 if language != "original" else 1.5
                got_naive = floats(lines_with(h, "naive"))[0]
                got_zig = floats(lines_with(h, "zig-zag"))[0]
                self.assertAlmostEqual(got_naive, naive, delta=0.001 + slack)
                self.assertAlmostEqual(got_zig, zig_zag, delta=0.001 + slack)
                self.assertLess(got_zig, got_naive)
                self.assertEqual(w.items, items)
                self.assertEqual([(t.entity, t.ground) for t in w.tiles], tiles)
                self.assertEqual((w.x, w.y), (0, 0))  # the trial's drone moved, ours did not
                # Two simulations were asked for, at 200 ticks each, on our own clock.
                self.assertGreaterEqual(w.run_ticks, 2 * data.ACTION_TICKS)


